    /// <summary>
    /// Spec 7.2.4: Window dressing — mutual funds buy winners, sell losers at quarter end.
    /// </summary>
    private void ApplyWindowDressing(IReadOnlyList<Stock> stocks)
    {
        foreach (var stock in stocks)
        {
            if (stock.Traits.Contains("ETF")) continue;

            var dayReturn = stock.PreviousClose > 0
                ? (stock.CurrentPrice - stock.PreviousClose) / stock.PreviousClose
                : 0m;

            // Buy winners (positive momentum stocks)
            if (dayReturn > 0.03m && _rng.NextDouble() < 0.3)
            {
                var push = stock.CurrentPrice * 0.001m;
                stock.CurrentPrice = Math.Round(stock.CurrentPrice + push, 2);
                stock.DayVolume += (long)(stock.AverageVolume * 0.01);
            }
            // Sell losers
            else if (dayReturn < -0.03m && _rng.NextDouble() < 0.3)
            {
                var push = stock.CurrentPrice * 0.001m;
                stock.CurrentPrice = Math.Max(0.01m, Math.Round(stock.CurrentPrice - push, 2));
                stock.DayVolume += (long)(stock.AverageVolume * 0.01);
            }
        }

        _log.Debug("Window dressing active", new { dayCount = DayCount });
    }

    /// <summary>
    /// Spec 7.2.15: Activist short seller publishes short report on overvalued stock.
    /// Rare but high-impact event.
    /// </summary>
    private void TryGenerateShortReport(IReadOnlyList<Stock> stocks)
    {
        if (_rng.NextDouble() > 0.01) return; // ~1% daily = roughly every 100 trading days

        // Find an overvalued target
        var targets = stocks.Where(s =>
            !s.Traits.Contains("ETF") &&
            s.PERatio > 50 &&
            s.CurrentPrice > s.FairValue * 1.5m &&
            s.MarketCap > 1_000_000_000m
        ).ToList();

        if (targets.Count == 0) return;

        var target = targets[_rng.Next(targets.Count)];

        // Generate short report event
        var impact = -0.08f - (float)_rng.NextDouble() * 0.12f; // -8% to -20%
        var evt = new GameEvent
        {
            Type = EventType.Company,
            Severity = EventSeverity.Major,
            Sentiment = -0.8f,
            Headline = $"Activist short seller publishes critical report on {target.Name} ({target.Symbol}), alleging overvaluation",
            AffectedSymbols = new List<string> { target.Symbol },
            PriceEffect = impact,
            VolatilityMultiplier = 2.5f,
            VolumeMultiplier = 4.0f,
            DurationMinutes = 120,
            RemainingMinutes = 120,
            TriggeredAt = DateTime.MinValue, // Will be set by caller
        };
        NewsThisTick.Add(evt);

        // Increase short interest
        target.ShortInterest += target.SharesOutstanding * 0.02m;

        _log.Info("Short report generated", new { symbol = target.Symbol, impact });
    }

    /// <summary>
    /// Tax-loss harvesting: December selling pressure on YTD losers, January bounce-back.
    /// Real effect: stocks that performed worst in the year get sold in December for tax benefits.
    /// </summary>
    private void ApplyTaxLossHarvesting(IReadOnlyList<Stock> stocks, DateTime gameTime)
    {
        var month = gameTime.Month;
        if (month != 12 && month != 1) return;

        foreach (var stock in stocks)
        {
            if (stock.Traits.Contains("ETF")) continue;

            // YTD return approximation (using 20-day return as proxy)
            var ytdReturn = stock.Return20Day;

            if (month == 12 && ytdReturn < -0.05m) // December: sell losers
            {
                if (_rng.NextDouble() < 0.05) // 5% daily chance
                {
                    var sellPressure = stock.CurrentPrice * 0.0005m;
                    stock.CurrentPrice = Math.Max(0.01m, Math.Round(stock.CurrentPrice - sellPressure, 2));
                    stock.DayVolume += (long)(stock.AverageVolume * 0.005);
                }
            }
            else if (month == 1 && ytdReturn < -0.05m) // January: bounce back (buying oversold)
            {
                if (_rng.NextDouble() < 0.05)
                {
                    var buyPressure = stock.CurrentPrice * 0.0004m;
                    stock.CurrentPrice = Math.Round(stock.CurrentPrice + buyPressure, 2);
                    stock.DayVolume += (long)(stock.AverageVolume * 0.003);
                }
            }
        }
    }

    /// <summary>
    /// Spec 7.2.16: Corporate buyback — steady buy pressure on stocks with buyback programs.
    /// Simulated as a small upward bias on profitable large-cap stocks.
    /// </summary>
    private void ApplyCorporateBuybacks(IReadOnlyList<Stock> stocks)
    {
        foreach (var stock in stocks)
        {
            if (stock.Traits.Contains("ETF")) continue;
            if (stock.NetIncome <= 0 || stock.MarketCap < 5_000_000_000m) continue;

            // ~10% of eligible stocks have active buyback programs
            if (_rng.NextDouble() > 0.10) continue;

            // Steady buying: up to 25% of average daily volume (Rule 10b-18)
            var buyVolume = (long)(stock.AverageVolume * 0.005 * _rng.NextDouble());
            stock.DayVolume += buyVolume;

            // Small upward pressure
            var push = stock.CurrentPrice * 0.0002m * (decimal)_rng.NextDouble();
            stock.CurrentPrice = Math.Round(stock.CurrentPrice + push, 2);

            // === REALISM BATCH 2: Buybacks reduce SharesOutstanding ===
            // Companies repurchase ~0.01-0.03% of shares per buyback day
            var repurchasePct = 0.0001 + _rng.NextDouble() * 0.0002; // 0.01-0.03%
            var sharesRepurchased = (long)(stock.SharesOutstanding * repurchasePct);
            if (sharesRepurchased > 0 && stock.SharesOutstanding - sharesRepurchased > 1_000_000)
            {
                stock.SharesOutstanding -= sharesRepurchased;
            }
        }
    }
