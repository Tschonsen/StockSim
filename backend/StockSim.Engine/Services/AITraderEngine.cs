    // 14. INSIDER TRADER AI (Spec 7.2.14)
    // =====================================================

    private void ApplyInsiderTraderAI(Stock stock, IReadOnlyList<GameEvent> activeEvents)
    {
        // Insider traders cause unusual volume BEFORE company events
        // Check if there's an active company event for this stock
        foreach (var evt in activeEvents)
        {
            if (evt.Type != EventType.Company) continue;
            if (!evt.AffectedSymbols.Contains(stock.Symbol)) continue;

            // If event just started (first few ticks), generate pre-event volume
            if (evt.RemainingMinutes > evt.DurationMinutes - 10)
            {
                // 30-50% chance per stock per tick that insider trading occurs
                if (_rng.NextDouble() < 0.02)
                {
                    // Unusual volume spike (visible to attentive players)
                    var insiderVolume = (long)(stock.AverageVolume * 0.01 * (1 + _rng.NextDouble()));
                    stock.DayVolume += insiderVolume;

                    // Slight price pressure in event direction (insiders know the outcome)
                    var insiderPush = stock.CurrentPrice * 0.00002m * (decimal)Math.Sign(evt.PriceEffect);
                    stock.CurrentPrice = Math.Max(0.01m, Math.Round(stock.CurrentPrice + insiderPush, 2));
                }
            }
        }
    }

